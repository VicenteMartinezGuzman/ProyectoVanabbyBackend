package Modelos;

import java.math.BigDecimal;
import java.sql.Timestamp;

/**
 *
 * @author vicen
 */
public class Envio {

    private int envioId;
    private int pedidoId;       // FK -> pedido
    private int direccionId;    // FK -> direccion_cliente
    private Integer empleadoId; // FK -> empleado
    private BigDecimal costoEnvio;
    private Timestamp fechaSalida;
    private Timestamp fechaEntregaReal;
    private String notas;

    public Envio() {
    }

    public int getEnvioId() {
        return envioId;
    }

    public void setEnvioId(int envioId) {
        this.envioId = envioId;
    }

    public int getPedidoId() {
        return pedidoId;
    }

    public void setPedidoId(int pedidoId) {
        this.pedidoId = pedidoId;
    }

    public int getDireccionId() {
        return direccionId;
    }

    public void setDireccionId(int direccionId) {
        this.direccionId = direccionId;
    }

    public Integer getEmpleadoId() {
        return empleadoId;
    }

    public void setEmpleadoId(Integer empleadoId) {
        this.empleadoId = empleadoId;
    }

    public BigDecimal getCostoEnvio() {
        return costoEnvio;
    }

    public void setCostoEnvio(BigDecimal costoEnvio) {
        this.costoEnvio = costoEnvio;
    }

    public Timestamp getFechaSalida() {
        return fechaSalida;
    }

    public void setFechaSalida(Timestamp fechaSalida) {
        this.fechaSalida = fechaSalida;
    }

    public Timestamp getFechaEntregaReal() {
        return fechaEntregaReal;
    }

    public void setFechaEntregaReal(Timestamp fechaEntregaReal) {
        this.fechaEntregaReal = fechaEntregaReal;
    }

    public String getNotas() {
        return notas;
    }

    public void setNotas(String notas) {
        this.notas = notas;
    }
}
